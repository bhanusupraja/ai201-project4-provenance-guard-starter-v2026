import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0–1 signals into one 0–1 score. ← TODO (Milestone 4)

    Both inputs point the same way: higher means more likely AI. Your output
    should too.

    Args:
        model_score: from `detector.model_signal` — how predictable the text is.
        style_score: from `stylometry.style_signal` — the shape of the text.

    Returns:
        A float from 0.0 (confidently human) to 1.0 (confidently AI).

    ⚠️ **Write the rule down before you code it, and put the numbers in your
    README.** A weighted average is the obvious choice and it is not the only
    one. Things worth thinking about:

      - **What happens when they disagree?** One signal at 0.9 and the other at
        0.1 averages to 0.5 — "unsure". Is that what you want? It might be
        exactly right: two methods disagreeing IS uncertainty. Or you might
        decide one signal is more trustworthy when they split.

      - **Which way do you want to be wrong?** Weighting toward the signal that
        reads more human means fewer false accusations and more AI text
        getting through. There's no weighting that avoids the trade.

      - Milestone 4 asks you to find a case where your two signals split and
        write it down. That case is what this rule exists to handle.

    The weights in config.py are placeholders. Change them, or ignore them and
    write a different rule.
    """
    model_score = min(max(float(model_score), 0.0), 1.0)
    style_score = min(max(float(style_score), 0.0), 1.0)

    # Weighted average first. The model signal counts more (0.65) because
    # it reads the text; the style signal counts less (0.35) because it
    # only measures shape, which is cheap to change on purpose.
    combined = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )

    # Disagreement rule: when the two signals split by 0.50 or more, the
    # honest answer is uncertainty, not whichever signal happened to win.
    # Pull the combined score 40% of the way back toward 0.50, so a
    # 0.9 / 0.1 split lands near 0.55 (unsure) instead of 0.64
    # (almost high-confidence AI on one signal's say-so).
    if abs(model_score - style_score) >= 0.50:
        combined = combined + 0.40 * (0.50 - combined)

    return round(min(max(combined, 0.0), 1.0), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into a guess and the text a reader actually sees.
    ← TODO (Milestone 5)

    Returns:
        (guess, label_text) — where `guess` is a short machine-readable string
        like "ai" / "human" / "unsure", and `label_text` is the full sentence
        shown to a person.

    ⚠️ Write the label text for someone who has never heard the word
    "threshold".

        ✗ "human, 0.81 confidence"
        ✓ "We think this was probably written by a person."

    All three labels have to be **reachable**. If no score can produce one of
    them, your ranges have a gap — and Milestone 5 asks you to submit text that
    produces each one, which is how you'd find out.

    The hardest one to write is "unsure". It has to admit uncertainty without
    sounding like an accusation, because the person reading it may well have
    written every word themselves. Your breakout asks your group what they'd
    think if they got it on their own work. That question is the whole
    milestone.
    """
    # Thresholds are in config.py
    if score >= config.AI_THRESHOLD:
        return (
            "ai",
            "We think this was probably generated by AI. This is our system's "
            "best guess, not proof, and it can be wrong. If you wrote this "
            "yourself, you can appeal and a person will look at it again.",
        )
    if score <= config.HUMAN_THRESHOLD:
        return (
            "human",
            "We think this was probably written by a person. We did not find "
            "strong signs that it was generated by AI. If you think we got "
            "this wrong, you can appeal and a person will look at it again.",
        )
    return (
        "unsure",
        "We are not sure whether this was written by a person or generated "
        "by AI, so we are not calling it either way. Nothing about this "
        "piece has been decided against you. If you wrote it, you can appeal "
        "and tell us more, and a person will look at it again.",
    )


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
